"""T-ID compile-size scaling: compiled do-COAST size vs base circuit size.

Empirical check of the complexity exponent K that T-ID reports for an
estimand: build the base MD circuit for the mixed colliderdoor dataset at
increasing ``num_nodes`` N (random init, no training), compile the T-ID
COAST for ``P(Y|do(X))`` via :func:`experiments.utils.queries.compile_queries`,
and verify that the compiled circuit's ``num_parameters`` grows like the
T-ID prediction ``c * base**K`` with only the constant ``c`` fitted.

One N per subprocess (``--worker`` mode): at large N the product compilation
allocates quadratically and a memory-pressure SIGKILL must not abort the
sweep — the driver records the failure and moves on. Results are cached in
``experiments/results/k_scaling/results.json`` and the sweep is resumable.

Usage::

    PYTHONPATH=. python -m experiments.k_scaling                # sweep (default N grid) + plot
    PYTHONPATH=. python -m experiments.k_scaling --plot-only    # plot from cache
    PYTHONPATH=. python -m experiments.k_scaling --ns 4 8 16 32 # sweep a custom grid

Requires the colliderdoor dataset (data/colliderdoor_mix_ZXMd_Yc_100K,
generated by generate_synthetic_data.py — only the CSV header and the SCM
pickle are read; no training data is used).
"""

import argparse
import glob
import json
import logging
import os
import subprocess
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import torch
from matplotlib import ticker


logging.getLogger("aac.query").setLevel(logging.ERROR)

from experiments.plotting.styles import apply_paper_style  # noqa: E402
from experiments.utils.identification import identify_estimands  # noqa: E402
from experiments.utils.queries import compile_queries as compile_query_circuits  # noqa: E402
from src.construction.circuit_builder import create_md_circuit  # noqa: E402
from src.symbolic.arithmetic.nodes import CategoricalDistribution  # noqa: E402
from src.symbolic.vtree import VNode, VTree  # noqa: E402
from src.utils import BitSet  # noqa: E402


REPO_ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = REPO_ROOT / "data" / "colliderdoor_mix_ZXMd_Yc_100K"
OUT_DIR = REPO_ROOT / "experiments" / "results" / "k_scaling"
RESULTS = OUT_DIR / "results.json"
PLOT = OUT_DIR / "plot_K_scaling.png"

DEFAULT_NS = range(4, 64)  # integer grid; the OOM wall on this machine is ~N=45


def load_meta() -> dict:
    """Dataset metadata: variable ids, MD sets, SCM pickle path (no data load)."""
    obs_path = sorted(glob.glob(str(DATA_DIR / "observational_*.csv")))[0]
    scm_path = sorted(glob.glob(str(DATA_DIR / "scm_*.pkl")))[0]
    var_names = list(pd.read_csv(obs_path, nrows=0).columns)
    var_to_id = {v: i for i, v in enumerate(var_names)}
    return {
        "var_to_id": var_to_id,
        "var_to_name": {v: k for k, v in var_to_id.items()},
        "z_ids": [var_to_id["Z"]],
        "m_ids": [var_to_id["M"]],
        "x_id": var_to_id["X"],
        "y_id": var_to_id["Y"],
        "n_vars": len(var_names),
        "V_names": set(var_names),
        "md_sets": [
            {var_to_id["Z"], var_to_id["X"]},
            {var_to_id["Z"], var_to_id["M"], var_to_id["X"]},
        ],
        "md_set_names": [{"Z", "X"}, {"Z", "M", "X"}],
        "scm_path": scm_path,
    }


def build_joint(res: dict, num_nodes: int, seed: int = 0):
    """Base MD circuit for colliderdoor on the handcrafted vtree ``zx | my``.

    Root splits {Z, X} from {M, Y}, so both required determinisms ({Z,X} at
    the root, {Z,X,M} deeper in the compiled product) are representable.
    """
    torch.manual_seed(seed)
    z_id, x_id, m_id, y_id = res["z_ids"][0], res["x_id"], res["m_ids"][0], res["y_id"]
    vt = VTree()
    v_z = vt.add_node(VNode(BitSet([z_id]), md_set=BitSet([z_id])))
    v_x = vt.add_node(VNode(BitSet([x_id]), md_set=BitSet([x_id])))
    v_m = vt.add_node(VNode(BitSet([m_id]), md_set=BitSet([m_id])))
    v_y = vt.add_node(VNode(BitSet([y_id]), md_set=BitSet.universal()))
    v_zx = vt.add_node(VNode(BitSet([z_id, x_id]), md_set=BitSet([z_id, x_id])))
    vt.add_children(v_zx, v_z, v_x)
    v_my = vt.add_node(VNode(BitSet([m_id, y_id]), md_set=BitSet([m_id])))
    vt.add_children(v_my, v_m, v_y)
    v_root = vt.add_node(VNode(BitSet([z_id, x_id, m_id, y_id]), md_set=BitSet([z_id, x_id])))
    vt.add_children(v_root, v_zx, v_my)
    dists = {
        vid: CategoricalDistribution(var=vid, categories=[0, 1], probabilities=[0.5, 0.5])
        for vid in (z_id, x_id, m_id, y_id)
    }
    return create_md_circuit(
        dists,
        vt,
        num_nodes=num_nodes,
        initialize_weights=True,
        fairness_temperature=10.0,
        max_leaf_num_nodes=2,
    )


def identify(res: dict) -> dict:
    """Identify P(Y|do(X)) with T-ID (graph-only; no circuit needed)."""
    return identify_estimands({"identification": {}}, res)


def _worker(n: int, out_path: str) -> None:
    """Build the base circuit at num_nodes=n, compile the do-COAST, dump sizes."""
    res = load_meta()
    estimands = identify(res)
    ac = build_joint(res, num_nodes=n)
    base = ac.num_parameters()
    q = compile_query_circuits(ac, estimands, res)["q_do_ac"]
    result = {
        "n": n,
        "base": base,
        "compiled": q.num_parameters(),
        "K": estimands["info"]["complexity"],
    }
    with open(out_path, "w") as f:
        json.dump(result, f)


def run_one(n: int, timeout: int = 1200) -> dict:
    """Run one N in a subprocess; a missing JSON means the child was killed (OOM)."""
    out_path = OUT_DIR / f"_worker_n{n}.json"
    env = dict(os.environ, PYTHONPATH=str(REPO_ROOT))
    try:
        subprocess.run(
            [sys.executable, "-m", "experiments.k_scaling", "--worker", str(n), str(out_path)],
            cwd=str(REPO_ROOT),
            env=env,
            timeout=timeout,
            capture_output=True,
        )
    except subprocess.TimeoutExpired:
        return {"n": n, "base": None, "compiled": None, "error": "timeout"}
    if not out_path.exists():
        return {"n": n, "base": None, "compiled": None, "error": "killed (OOM)"}
    with open(out_path) as f:
        r = json.load(f)
    os.remove(out_path)
    return r


def sweep(ns) -> list:
    """Sweep N grid in subprocesses, resuming from the results cache."""
    rows = json.loads(RESULTS.read_text()) if RESULTS.exists() else []
    done = {r["n"] for r in rows}
    for n in ns:
        if n in done:
            continue
        r = run_one(n)
        rows.append(r)
        tag = (
            f"base={r['base']:8d} compiled={r['compiled']:10d}"
            if r["base"]
            else f"FAILED ({r['error']})"
        )
        print(f"N={n:3d}: {tag}", flush=True)
        RESULTS.write_text(json.dumps(rows, indent=1))
    return rows


def plot(rows: list, K: float) -> None:
    """Compiled do-query size vs base circuit size, against T-ID's y = c*x^K."""
    pts = sorted((r for r in rows if r.get("base")), key=lambda r: r["base"])
    xs = np.array([r["base"] for r in pts], dtype=float)
    ys = np.array([r["compiled"] for r in pts], dtype=float)

    # Reference: T-ID's prediction y = c * x**K with K fixed; only the constant
    # is least-squares (in log space).
    log_c = float(np.mean(np.log2(ys) - K * np.log2(xs)))
    ref = 2**log_c * xs**K
    ss_res = float(np.sum((np.log2(ys) - np.log2(ref)) ** 2))
    ss_tot = float(np.sum((np.log2(ys) - np.log2(ys).mean()) ** 2))
    r2 = 1 - ss_res / ss_tot

    apply_paper_style()
    fig, ax = plt.subplots(figsize=(3.5, 2.8))

    # Okabe-Ito: vermillion for the measured do-query circuit, blue for the
    # T-ID prediction (cf. experiments/plot_x_support_slices.py).
    blue, vermillion = "#0072B2", "#D55E00"
    grid = np.linspace(xs.min(), xs.max(), 300)
    ax.plot(
        grid,
        2**log_c * grid**K,
        ls="--",
        color=blue,
        lw=1.6,
        label=rf"T-ID prediction: $|\mathcal{{C}}_{{do}}|=\mathcal{{O}}(|\mathcal{{C}}_{{\rm base}}|^{K:g})$, $K={K:g}$",
        zorder=2,
    )
    ax.plot(
        xs,
        ys,
        "o-",
        color=vermillion,
        ms=4,
        lw=1.5,
        zorder=3,
        label="compiled do-query circuit",
    )

    ax.set_xlabel(r"$|\mathcal{C}_{\text{base}}|$", fontsize=10)
    ax.set_ylabel(r"$|\mathcal{C}_{do}|$", fontsize=10)
    ax.grid(True, alpha=0.3, linewidth=0.5)
    ax.tick_params(labelsize=9)
    for axis in (ax.xaxis, ax.yaxis):
        axis.set_major_formatter(ticker.ScalarFormatter(useMathText=True, useOffset=False))
        axis.get_major_formatter().set_scientific(True)
        axis.get_major_formatter().set_powerlimits((0, 0))
    ax.legend(loc="upper left", frameon=False, fontsize=8)

    fig.tight_layout(pad=0.6)
    fig.savefig(PLOT, dpi=150, bbox_inches="tight")
    print(f"\n{len(pts)} points, base {int(xs.min())}..{int(xs.max())}")
    print(f"T-ID K = {K:g}; fixed-slope fit R^2 = {r2:.4f}")
    print(f"saved: {PLOT}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--worker", type=int, metavar="N", help=argparse.SUPPRESS)
    ap.add_argument("worker_out", nargs="?", help=argparse.SUPPRESS)
    ap.add_argument("--ns", type=int, nargs="+", default=None, help="custom N grid")
    ap.add_argument("--plot-only", action="store_true", help="skip the sweep, plot from cache")
    args = ap.parse_args()

    if args.worker is not None:
        _worker(args.worker, args.worker_out)
        return

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rows = json.loads(RESULTS.read_text()) if RESULTS.exists() else []
    K = rows[0].get("K") if rows else None
    if K is None:
        K = identify(load_meta())["info"]["complexity"]
    print(f"T-ID complexity K = {K}")

    if not args.plot_only:
        rows = sweep(args.ns if args.ns is not None else DEFAULT_NS)
    plot(rows, K)


if __name__ == "__main__":
    main()
